export function archiveDayGuide(kind: string): ArchiveStateGuide {
  return Object.prototype.hasOwnProperty.call(archiveDayGuides, kind) ? archiveDayGuides[kind]! : {
    label: `未识别状态（${kind}）`, meaning: '当前页面无法解释这个状态，不推断已完成或失败。',
    entry: '收到当前页面未支持的状态。', next: '核对配套版本后重新读取状态。', action: '保留状态代码并核对 Server、Agent 与前端版本。',
  }
}
